def render_extlinux(state: str, fdt_path: str, previous_overlays: str = "") -> str | None:
    """Return extlinux.conf content for the given state, with {FDT} substituted.

    Returns None for 'empty' → caller should not create the file.
    """
    if state == "empty":
        return None
    tpl_path = f"{EXTLINUX_TPL}/{state}.conf"
    with open(tpl_path) as f:
        tpl = f.read()
    basename_no_ext = os.path.splitext(os.path.basename(fdt_path))[0]
    return (tpl
            .replace("{FDT}", fdt_path)
            .replace("{FDT_BASENAME_NO_EXT}", basename_no_ext)
            .replace("{PREVIOUS_OVERLAYS}", previous_overlays))


