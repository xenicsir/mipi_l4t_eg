def _pass(msg: str) -> None:  print(f"  {GREEN}PASS {NC} {msg}")
def _xfail(msg: str) -> None: print(f"  {GREEN}XFAIL{NC} {msg}")
def _xpass(msg: str) -> None: print(f"  {YELLOW}XPASS{NC} {msg}")
def _fail(msg: str) -> None:  print(f"  {RED}FAIL {NC} {msg}")
def _skip(msg: str) -> None:  print(f"  {YELLOW}SKIP {NC} {msg}")


# ---------------------------------------------------------------------------
# Expected outcomes — predict how the script SHOULD behave
# ---------------------------------------------------------------------------
# Outcome tags:
#   "pass"   — script exits 0 and behavior assertions hold
#   "xfail:<reason>" — script exits non-zero with a specific, expected reason
#     e.g. "xfail:port_rejected_in_2ports_mode"

def will_use_2ports(entry: Entry) -> bool:
    """True iff the script will switch base_devicetree to 'Exosens Cameras - 2 ports'.
    This happens only for Auvidea X230D on L4T 35.1 (kernel DTB lacks channel@2).
    """
    if entry.platform_id != "agx_orin_x230d" or entry.version != "35.1":
        return False
    # The 2-port DTBO must be in the build output (only 35.1 AGX concord builds it)
    twoports = f"{entry.dtbo_boot_dir}/{entry.dtbo_base_prefix}-cams-dione-2ports.dtbo"
    return os.path.exists(twoports)


def expected_outcome(entry: Entry, state: str, port: int, camera: str) -> tuple[str, str]:
    """Return (outcome, reason) for this combination.

    outcome ∈ {"pass", "xfail:<name>"}.
    """
    # ─── Boards where the kernel DTB lacks channel@2/@3 (Auvidea X230D on L4T 35.1)
    is_2port_board = (entry.platform_id == "agx_orin_x230d" and entry.version == "35.1")

    # 2-port mode requires the script to detect the limitation via LABEL primary
    # in extlinux.conf (the only reliable source). States without it cause the
    # script to fall back to the regular 4-port overlay which fails fdtoverlay
    # on the 2-channel kernel DTB. This is the documented behavior.
    if is_2port_board and state in ("empty", "no_primary"):
        return ("xfail:no_label_primary_2port_board",
                "extlinux.conf lacks LABEL primary → script cannot detect the "
                "2-channel kernel DTB → regular 4-port DTBO fails fdtoverlay")

    # 2-port mode detection succeeded, but port ≥ 2 is not exposed on the board.
    # Script rejects with explicit "port X not available" error.
    if will_use_2ports(entry) and state not in ("empty", "no_primary") and port >= 2:
        return ("xfail:port_rejected_in_2ports_mode",
                "no channel@2 in kernel DTB, script guards against port ≥ 2")

    return "pass", ""


