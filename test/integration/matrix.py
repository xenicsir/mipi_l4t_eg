def run_script(entry: Entry, port: int, camera: str,
               overlay_map: dict[str, str], env_overrides: dict[str, str]) -> tuple[int, str, str]:
    cbh_log = f"{BOOT_DIR}/cbh_calls.log"
    overlays_file = f"{BOOT_DIR}/overlays.txt"
    write_overlays_file(overlay_map, overlays_file)

    env = os.environ.copy()
    env.update({
        "TEST_BOARD_SHORT":      entry.board_short,
        "TEST_CAMERA_PORTS":     str(entry.ports),
        "TEST_L4T_MODE":         entry.l4t_mode,
        "TEST_BASE_DTB":         entry.base_dtb,
        "TEST_BOOT_DIR":         BOOT_DIR,
        "TEST_OVERLAY_DTBO_JSON": json.dumps(overlay_map),
        "TEST_CBH_LOG":          cbh_log,
        "TEST_OVERLAYS_FILE":    overlays_file,
        "TEST_PROC_DT":          PROC_DT,
    })
    env.update(env_overrides)

    r = subprocess.run(
        ["bash", SCRIPT, f"{port}/{camera}"],
        env=env, capture_output=True, text=True,
    )
    return r.returncode, r.stdout, r.stderr


# ---------------------------------------------------------------------------
# Merged DTB retrieval (36.x) — apply fdtoverlay sequentially
# ---------------------------------------------------------------------------

def get_merged_dtb_36x() -> tuple[str | None, str]:
    extlinux = f"{BOOT_DIR}/extlinux/extlinux.conf"
    if not os.path.exists(extlinux):
        return None, "no extlinux.conf"

    content = open(extlinux).read()
    # Extract the JetsonIO block's FDT + OVERLAYS
    jio = re.search(r"LABEL JetsonIO(.+?)(?=^LABEL |\Z)", content, re.S | re.M)
    if not jio:
        return None, "no JetsonIO label"
    block = jio.group(1)
    fdt_m = re.search(r"^\s*FDT\s+(\S+)", block, re.M)
    ovl_m = re.search(r"^\s*OVERLAYS\s+(\S+)", block, re.M)
    if not fdt_m:
        return None, "no FDT in JetsonIO block"

    fdt = fdt_m.group(1)
    dtbos = ovl_m.group(1).split(",") if ovl_m else []

    current = fdt
    tmp_files = []
    for i, dtbo in enumerate(dtbos):
        out = tempfile.mktemp(suffix=f".{i}.dtb", dir="/tmp")
        r = subprocess.run(["fdtoverlay", "-i", current, "-o", out, dtbo],
                           capture_output=True, text=True)
        if r.returncode != 0:
            for f in tmp_files:
                try: os.remove(f)
                except OSError: pass
            return None, r.stderr.strip()
        if current != fdt:
            try: os.remove(current)
            except OSError: pass
        tmp_files.append(out)
        current = out

    return current, ""


