def setup_proc_dt(entry: Entry, dtb_path: str, state: str) -> None:
    """Populate /tmp/fake_proc_dt from the base DTB (or from merged DTB if state=previously_eg).

    In state='previously_eg' we simulate that a previous install's user-custom.dtb is
    what's currently booted — the script should read /proc/device-tree and find NO
    rbpcv2_imx219 directories (because they were already disabled or removed), but the
    new code path reads the primary kernel DTB which DOES have them. The test verifies
    the script detects IMX219 in the base DTB and passes the disable arg.
    """
    shutil.rmtree(PROC_DT, ignore_errors=True)
    os.makedirs(PROC_DT, exist_ok=True)

    # compatible string (mock grep maps /proc/device-tree → PROC_DT)
    with open(f"{PROC_DT}/compatible", "w") as f:
        f.write(entry.compat)

    # In 'previously_eg' state, /proc reflects a merged user-custom DTB where IMX was
    # already disabled — so we intentionally create NO imx219 directories.
    if state == "previously_eg":
        return

    # Otherwise (fresh, no_primary): /proc reflects the base kernel DTB directly.
    r = subprocess.run(
        ["dtc", "-I", "dtb", "-O", "dts", dtb_path],
        capture_output=True, text=True,
    )
    if r.returncode != 0:
        return

    dts = r.stdout
    for pattern in ("rbpcv2_imx219", "rbpcv3_imx477"):
        for m in re.finditer(r"(" + pattern + r"[^\s{]*)\s*\{", dts):
            node_name = m.group(1)
            os.makedirs(f"{PROC_DT}/{node_name}", exist_ok=True)


