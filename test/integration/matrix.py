def build_overlay_map(entry: Entry) -> dict[str, str]:
    boot = entry.dtbo_boot_dir
    bpfx = entry.dtbo_base_prefix
    lpfx = entry.dtbo_lane_prefix
    ports = entry.ports
    is_forecr = entry.is_forecr

    m: dict[str, str] = {}

    # Base overlay
    base_key = "Exosens Cameras for DSBOARD-ORNXS" if is_forecr else "Exosens Cameras"
    base_dtbo = f"{boot}/{bpfx}-cams-dione.dtbo"
    if os.path.exists(base_dtbo):
        m[base_key] = base_dtbo

    # Global variant (tegra234 only)
    global_dtbo = f"{boot}/{bpfx}-cams-dione-global.dtbo"
    if os.path.exists(global_dtbo):
        m["Exosens Cameras (global)"] = global_dtbo

    # 2-port variant (35.1 AGX Orin concord only)
    twoports_dtbo = f"{boot}/{bpfx}-cams-dione-2ports.dtbo"
    if os.path.exists(twoports_dtbo):
        m["Exosens Cameras - 2 ports"] = twoports_dtbo

    # Disable overlays
    for imx in ("imx219", "imx477"):
        dtbo = f"{boot}/{bpfx}-cams-disable-{imx}.dtbo"
        if os.path.exists(dtbo):
            m[f"Exosens Cameras. Disable {imx}"] = dtbo

    # Per-port lane overlays
    lane_suffixes = {
        "ec-1-lane":  "EC_1_lane",
        "ec-2-lanes": "EC_2_lanes",
        "ilumos":     "iLumos",
        "microlynx":  "Microlynx",
    }
    for port in range(ports):
        for suffix, lane in lane_suffixes.items():
            dtbo = f"{boot}/{lpfx}-cam{port}-{suffix}.dtbo"
            if os.path.exists(dtbo):
                m[f"Exosens Cameras. CAM{port}:{lane}"] = dtbo

    return m


def write_overlays_file(overlay_map: dict[str, str], path: str) -> None:
    with open(path, "w") as f:
        f.write("Header 2: Jetson CSI Connector\n")
        f.write("  Available hardware modules:\n")
        for i, name in enumerate(overlay_map, 1):
            f.write(f"  {i}. {name}\n")


