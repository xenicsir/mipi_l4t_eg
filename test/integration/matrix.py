def populate_boot_dtbos(entry: Entry) -> None:
    """Symlink every DTBO from the build output into /boot (one-time per entry).

    The script does `[[ -f /boot/<prefix>-cams-dione-2ports.dtbo ]]` for 2-port
    detection — the file must exist as a concrete /boot/*.dtbo entry.
    """
    for f in os.listdir(BOOT_DIR):
        if f.endswith(".dtbo"):
            try:
                os.remove(os.path.join(BOOT_DIR, f))
            except OSError:
                pass
    if os.path.isdir(entry.dtbo_boot_dir):
        for f in os.listdir(entry.dtbo_boot_dir):
            if f.endswith(".dtbo"):
                src = os.path.join(entry.dtbo_boot_dir, f)
                dst = os.path.join(BOOT_DIR, f)
                try:
                    os.symlink(src, dst)
                except OSError:
                    shutil.copy(src, dst)


def populate_boot(entry: Entry, state: str) -> None:
    """Reset per-test state in /boot (extlinux.conf + stale artefacts)."""
    shutil.rmtree(f"{BOOT_DIR}/extlinux", ignore_errors=True)
    os.makedirs(f"{BOOT_DIR}/extlinux", exist_ok=True)
    for f in ("kernel_merged.dtb", "cbh_calls.log"):
        p = f"{BOOT_DIR}/{f}"
        if os.path.exists(p):
            os.remove(p)
    content = render_extlinux(state, entry.base_dtb)
    if content is not None:
        with open(f"{BOOT_DIR}/extlinux/extlinux.conf", "w") as f:
            f.write(content)
    # 'empty' state: do not create the file at all


